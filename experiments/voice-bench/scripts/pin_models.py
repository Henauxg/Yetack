# Pins each model of the bench to a Hugging Face commit, with the SHA-256 and size of every file.
import json, sys, urllib.request

UA = {"User-Agent": "voice-bench (model pinning)"}

def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA)) as r:
        return json.load(r)

MODELS = [
    # id, repo, files or folder, license, note
    ("nemotron-en-q8", "handy-computer/nemotron-speech-streaming-en-0.6b-gguf", ["nemotron-speech-streaming-en-0.6b-Q8_0.gguf"], "NVIDIA Open Model License", "English, cache-aware streaming"),
    ("nemotron-en-q4", "handy-computer/nemotron-speech-streaming-en-0.6b-gguf", ["nemotron-speech-streaming-en-0.6b-Q4_K_M.gguf"], "NVIDIA Open Model License", "the same, 4-bit"),
    ("unified-en-q8", "handy-computer/parakeet-unified-en-0.6b-gguf", ["parakeet-unified-en-0.6b-Q8_0.gguf"], "NVIDIA Open Model License", "English, offline and buffered streaming"),
    ("tdt-v3-q8", "handy-computer/parakeet-tdt-0.6b-v3-gguf", ["parakeet-tdt-0.6b-v3-Q8_0.gguf"], "CC-BY-4.0", "25 languages, offline"),
    ("ultra-q8", "handy-computer/parakeet-ultra-gguf", ["parakeet-ultra-Q8_0.gguf"], "CC-BY-4.0", "Moondream's tuned Parakeet TDT, 25 languages, offline"),
    ("whisper-turbo-q8", "handy-computer/whisper-large-v3-turbo-gguf", ["whisper-large-v3-turbo-Q8_0.gguf"], "MIT", "99 languages, offline, initial prompt"),
    ("moonshine-medium-q8", "handy-computer/moonshine-streaming-medium-gguf", ["moonshine-streaming-medium-Q8_0.gguf"], "see model card", "English, streaming"),
    ("qwen3-asr-0.6b-q8", "handy-computer/Qwen3-ASR-0.6B-gguf", ["Qwen3-ASR-0.6B-Q8_0.gguf"], "Apache-2.0", "LLM decoder, context prompt"),
    ("silero-vad", "handy-computer/silero-vad-v6.2-gguf", ["silero-vad-v6.2-F32.gguf"], "MIT", "voice detection, for the pauses"),
    ("nemotron-en-onnx", "altunenes/parakeet-rs", "nemotron-speech-streaming-en-0.6b", "NVIDIA Open Model License", "ONNX export for parakeet-rs, fp32"),
    ("unified-en-onnx", "altunenes/parakeet-rs", "parakeet-unified-en-0.6b", "NVIDIA Open Model License", "ONNX export for parakeet-rs, fp32"),
]

out = ["# Generated by pin_models.py: each model pinned to a Hugging Face commit, with the SHA-256",
       "# of every file. The driver's `fetch` refuses a file whose hash differs.", ""]
for mid, repo, files, license, note in MODELS:
    info = get(f"https://huggingface.co/api/models/{repo}")
    rev = info["sha"]
    if isinstance(files, str):
        tree = get(f"https://huggingface.co/api/models/{repo}/tree/{rev}/{files}?recursive=true")
        entries = [x for x in tree if x["type"] == "file" and not x["path"].endswith("README.md")]
        folder = True
    else:
        tree = get(f"https://huggingface.co/api/models/{repo}/tree/{rev}")
        entries = [x for x in tree if x["type"] == "file" and x["path"] in files]
        folder = False
        assert len(entries) == len(files), (mid, [x["path"] for x in tree])
    out.append("[[model]]")
    out.append(f'id = "{mid}"')
    out.append(f'repo = "{repo}"')
    out.append(f'revision = "{rev}"')
    out.append(f'folder = {"true" if folder else "false"}')
    out.append(f'license = "{license}"')
    out.append(f'note = "{note}"')
    for x in entries:
        lfs = x.get("lfs")
        sha = lfs["oid"] if lfs else None
        if sha is None:
            # A small file outside LFS: hash its bytes.
            import hashlib
            data = urllib.request.urlopen(urllib.request.Request(f"https://huggingface.co/{repo}/resolve/{rev}/{x['path']}", headers=UA)).read()
            sha = hashlib.sha256(data).hexdigest()
        out.append("[[model.file]]")
        out.append(f'path = "{x["path"]}"')
        out.append(f'size = {x["size"]}')
        out.append(f'sha256 = "{sha}"')
    out.append("")
sys.stdout.write("\n".join(out))
